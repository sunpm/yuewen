"""Generate PC UI font subsets; keep full fonts for arbitrary text and exports.

Run with Python + fonttools[woff]==4.60.2 after changing UI copy.
"""

from pathlib import Path

from fontTools import subset
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parent.parent
characters = set(range(32, 127))
for directory in (root / "web/src", root / "shared"):
    for source in directory.rglob("*"):
        if source.suffix in (".ts", ".tsx", ".json"):
            characters.update(map(ord, source.read_text()))

rules = []
for weight, style in ((400, "Regular"), (500, "Medium")):
    filename = f"LXGWWenKaiLite-{style}"
    font = TTFont(root / f"web/public/fonts/{filename}.woff2")
    codepoints = sorted(characters & font.getBestCmap().keys())
    options = subset.Options()
    options.flavor = "woff2"
    options.name_IDs = ["*"]
    options.name_legacy = True
    options.name_languages = ["*"]
    sub = subset.Subsetter(options=options)
    sub.populate(unicodes=codepoints)
    sub.subset(font)
    font.save(root / f"web/public/fonts/{filename}-pc.woff2")
    for suffix, unicode_range in (("", ""), ("-pc", ",".join(f"U+{c:X}" for c in codepoints))):
        rules.append(
            "@font-face {\n"
            "  font-family: 'LXGW WenKai Lite';\n"
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            "  font-display: swap;\n"
            f"  src: url('/fonts/{filename}{suffix}.woff2') format('woff2');\n"
            + (f"  unicode-range: {unicode_range};\n" if unicode_range else "")
            + "}\n"
        )

(root / "web/src/fonts.css").write_text(
    "/* Generated by scripts/subset-pc-fonts.py. Full fonts cover all other characters. */\n"
    + "".join(rules)
    + ":root {\n  --font-reading: 'LXGW WenKai Lite', 'Kaiti SC', 'KaiTi', 'PingFang SC', sans-serif;\n}\n"
)
